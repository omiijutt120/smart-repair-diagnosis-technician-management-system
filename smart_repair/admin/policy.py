def can_edit(resource, record=None):
    if resource not in EDIT_FIELDS or (record and record.archived_at):
        return False
    if resource == "roles" and record and record.is_system:
        return False
    if resource in {"purchase_orders", "estimates"} and record and record.status != "Draft":
        return False
    if resource == "purchase_order_items" and record and record.order.status != "Draft":
        return False
    if resource == "estimate_lines" and record and record.estimate.status != "Draft":
        return False
    if resource == "repair_job_services" and record:
        job = db.session.get(RepairJob, record.repair_job_id)
        return job.status in {"Assigned", "Inspection", "On Hold"}
    return True


def build_form(resource, record=None):
    model = MODELS[resource]
    fields = {}
    for name in EDIT_FIELDS.get(resource, "").split():
        col = model.__table__.columns[name]
        label = name.removesuffix("_id").replace("_", " ").title()
        validators = [Optional()] if col.nullable or col.default is not None else [DataRequired()]
        if col.foreign_keys:
            target = next(iter(col.foreign_keys)).column.table.name
            choices = [(r.id, str(r)) for r in MODELS[target].query.filter_by(archived_at=None).limit(1000).all()]
            if col.nullable:
                choices.insert(0, (0, "None"))
            fields[name] = SelectField(label, choices=choices, coerce=int, validators=[Optional()] if col.nullable else [DataRequired()])
        elif name in SELECTS:
            fields[name] = SelectField(label, choices=[(v, v) for v in SELECTS[name]], validators=[DataRequired()])
        elif isinstance(col.type, Boolean):
            fields[name] = BooleanField(label, default=col.default.arg if col.default and not callable(col.default.arg) else False)
        elif isinstance(col.type, Integer):
            maximum = 5 if name == "proficiency_level" else 1000000
            minimum = 1 if name in {"weight", "quantity", "quantity_ordered", "proficiency_level"} else 0
            fields[name] = IntegerField(label, validators=[Optional() if col.nullable else NumberRange(min=minimum, max=maximum), NumberRange(min=minimum, max=maximum)])
        elif isinstance(col.type, Numeric):
            fields[name] = DecimalField(label, places=2, validators=[NumberRange(min=0, max=99999999)])
        elif isinstance(col.type, DateTime):
            fields[name] = DateTimeLocalField(label, format="%Y-%m-%dT%H:%M", validators=validators)
        elif isinstance(col.type, Date):
            fields[name] = DateField(label, validators=validators)
        elif isinstance(col.type, Time):
            fields[name] = TimeField(label, validators=validators)
        elif isinstance(col.type, Text):
            fields[name] = TextAreaField(label, validators=validators + [Length(max=5000)])
        else:
            validators.append(Length(max=col.type.length or 255))
            if name == "email":
                validators.append(email_address)
            if name == "phone":
                validators.append(Regexp(r"^\+?[0-9 ()-]{7,25}$", message="Enter a valid phone number."))
            fields[name] = StringField(label, validators=validators)
    if resource == "users":
        fields["new_password"] = PasswordField("New password" if record else "Password", validators=[Optional() if record else DataRequired(), Length(min=8, max=128)])
    form_type = type(f"{model.__name__}Form", (FlaskForm,), fields)
    return form_type(obj=record)


def populate(resource, form, record, actor_id):
    for name in EDIT_FIELDS[resource].split():
        value = form[name].data
        if record.__table__.columns[name].foreign_keys and value == 0:
            value = None
        if isinstance(value, str):
            value = value.strip()
            if name == "email":
                value = value.lower()
            if not value and record.__table__.columns[name].nullable:
                value = None
        setattr(record, name, value)
    if resource == "users" and form.new_password.data:
        record.set_password(form.new_password.data)
    if resource == "purchase_orders" and not record.id:
        record.created_by_user_id = actor_id
    if resource == "purchase_order_items" and not record.id:
        record.quantity_received = 0


def check_availability_assignments(slot):
    for assignment in TechnicianAssignment.query.filter_by(technician_id=slot.technician_id, status="Active").all():
        for appointment in assignment.request.appointments:
            start = local_datetime(appointment.scheduled_start)
            if appointment.status == "Scheduled" and start.date() == slot.available_date:
                raise BusinessError("This date has an active assignment. Reassign it before changing availability.")


def validate_record(resource, record, actor_id, original=None):
    if resource == "users" and record.id == actor_id and not record.is_active:
        raise BusinessError("You cannot deactivate your own administrator account.")
    if resource == "user_roles":
        role = db.session.get(Role, record.role_id)
        user = db.session.get(User, record.user_id)
        if role.name == "Customer" and not user.customer:
            db.session.add(CustomerProfile(user_id=user.id))
        if role.name == "Technician" and not user.technician:
            raise BusinessError("Create the technician profile before assigning the Technician role.")
        if original and original.get("user_id") == actor_id:
            previous_role = db.session.get(Role, original["role_id"])
            if previous_role.name == "Admin" and (record.role_id != previous_role.id or record.user_id != actor_id):
                raise BusinessError("You cannot remove your own administrator role.")
    if resource in {"customer_profiles", "technician_profiles"}:
        if original and original["user_id"] != record.user_id:
            raise BusinessError("A profile's login identity cannot be reassigned.")
    if resource == "customer_devices":
        if record.purchase_date and record.purchase_date > local_now().date():
            raise BusinessError("Purchase date cannot be in the future.")
        if original and RepairRequest.query.filter_by(customer_device_id=record.id).first():
            if record.customer_id != original["customer_id"] or record.device_model_id != original["device_model_id"]:
                raise BusinessError("A device with repair history cannot change owner or model.")
    if resource == "service_centers" and record.closing_time <= record.opening_time:
        raise BusinessError("Closing time must be after opening time.")
    if resource == "technician_availability":
        if record.id:
            check_availability_assignments(record)
        validate_availability(record)
    if resource == "purchase_orders" and record.expected_date and record.expected_date < record.order_date:
        raise BusinessError("Expected delivery must not precede the order date.")
    if resource in {"purchase_order_items", "estimate_lines"}:
        parent = db.session.get(PurchaseOrder if resource == "purchase_order_items" else Estimate,
            record.purchase_order_id if resource == "purchase_order_items" else record.estimate_id)
        if parent.status != "Draft" or parent.archived_at:
            raise BusinessError("Only a draft's line items may be changed.")
        if original:
            parent_key = "purchase_order_id" if resource == "purchase_order_items" else "estimate_id"
            if original[parent_key] != getattr(record, parent_key):
                raise BusinessError("A line item cannot be moved to another document.")
        if resource == "estimate_lines":
            if bool(record.service_id) == bool(record.spare_part_id):
                raise BusinessError("Choose exactly one service or spare part.")
            record.line_total = record.quantity * record.unit_price
    if resource == "repair_job_services":
        job = db.session.get(RepairJob, record.repair_job_id)
        if job.status not in {"Assigned", "Inspection", "On Hold"}:
            raise BusinessError("Service lines may only be changed before customer approval.")


def recalculate_parent(resource, record):
    if resource == "purchase_order_items":
        order = db.session.get(PurchaseOrder, record.purchase_order_id)
        db.session.expire(order, ["items"])
        order.total_amount = sum(i.quantity_ordered * i.unit_cost for i in order.items if not i.archived_at)
    if resource in {"estimates", "estimate_lines"}:
        from smart_repair.services.billing import recalculate
        estimate = record if resource == "estimates" else db.session.get(Estimate, record.estimate_id)
        db.session.expire(estimate, ["lines"])
        recalculate(estimate)
